def eval_nomadic(model, splits, phase_tags, cfg, use_policy=True):
    model.eval(); X, Y, R = splits['test']['X'], splits['test']['Y'], splits['test']['R']
    tracker = HybridDeltaTracker(cfg, cfg.device); tracker.reset()
    all_y, all_gate, batch_tags, batch_ents = [], [], [], []

    prev_yb = torch.zeros((cfg.batch_size, cfg.output_dim), device=cfg.device)

    with torch.no_grad():
        for i in range(0, len(X), cfg.batch_size):
            xb, yb, rb = X[i:i+cfg.batch_size], Y[i:i+cfg.batch_size], R[i:i+cfg.batch_size]
            if prev_yb.size(0) != xb.size(0): prev_yb = torch.zeros((xb.size(0), cfg.output_dim), device=cfg.device)

            z = torch.zeros((xb.size(0), 1), device=cfg.device)
            warm_mse = F.mse_loss(model(xb, z, z, cfg.temperature)[0], prev_yb) # Lagged
            dh, de, derr, dh_val, s2, dtau = tracker.compute(xb, warm_mse)
            de_t = torch.full((xb.size(0), 1), derr, device=cfg.device)

            _, pg, _, pe = model(xb, dh, de_t, cfg.temperature)
            ee, gap = exp_signals(prev_yb, (pg.unsqueeze(-1)*pe).sum(1), pe, pg) # Lagged
            phi = phi_signal(de, derr, ee, gap, cfg)
            t_now = cfg.temp_stable + (cfg.temp_transition - cfg.temp_stable) * float(phi.item())

            y_hat, gp, _, eo = model(xb, dh, de_t, t_now)

            if use_policy:
                pi = torch.cat([xb, dh, de_t, torch.full((xb.size(0),1), float(phi.item()), device=xb.device), torch.full((xb.size(0),1), s2, device=xb.device), torch.full((xb.size(0),1), dtau, device=xb.device)], dim=-1)
                ss, tp, mp = model.policy(pi)
                eff = cfg.policy_mix_weight * float(ss[:, 1].mean().item())
                tgt = (F.one_hot(torch.argmax(tp.mean(0)), cfg.num_experts).float().unsqueeze(0).expand(xb.size(0), -1) - gp).detach() + gp
                mx = (1.0 - eff)*gp + eff*tgt
                gp = F.one_hot(mx.argmax(-1), cfg.num_experts).float() if (cfg.use_hard_switch and (mp[:, 1].mean().item() > 0.5) and not (dh_val > cfg.phi_hard_threshold)) else mx
                y_hat = (gp.unsqueeze(-1) * eo).sum(1)

            all_y.append(y_hat); all_gate.append(gp); bi = i // cfg.batch_size
            batch_tags.append(phase_tags[bi] if bi < len(phase_tags) else 'stable_unknown')
            batch_ents.append(gate_entropy(gp).mean().item())
            prev_yb = yb.detach()

    mse = F.mse_loss(torch.cat(all_y), Y).item()
    sh = [e for t, e in zip(batch_tags, batch_ents) if t.startswith('stable_')]
    th = [e for t, e in zip(batch_tags, batch_ents) if t.startswith('transition_')]
    return mse, {'stable_entropy_mean': float(np.mean(sh)) if sh else float('nan'), 'transition_entropy_mean': float(np.mean(th)) if th else float('nan'), 'mean_switch_latency': 0.0}

def train_nomadic_full(cfg, splits, phase_tags):
    model = NomadicMoE(cfg.input_dim, cfg.hidden_dim, cfg.output_dim, cfg.num_experts, cfg.gate_hidden_dim, cfg.policy_hidden_dim).to(cfg.device)
    opt = torch.optim.Adam(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    X_tr, Y_tr, R_tr = splits['train']['X'], splits['train']['Y'], splits['train']['R']
    mse_log, dyn_log = [], []

    for epoch in range(cfg.epochs):
        model.train(); tracker = HybridDeltaTracker(cfg, cfg.device); tracker.reset()
        dw = DwellTimeRegularizer(cfg.tau_k_min, cfg.tau_k_penalty); dw.reset()
        prev_yb = torch.zeros((cfg.batch_size, cfg.output_dim), device=cfg.device)

        for i in range(0, len(X_tr), cfg.batch_size):
            xb, yb, rb = X_tr[i:i+cfg.batch_size], Y_tr[i:i+cfg.batch_size], R_tr[i:i+cfg.batch_size]
            opt.zero_grad()
            if prev_yb.size(0) != xb.size(0): prev_yb = torch.zeros((xb.size(0), cfg.output_dim), device=cfg.device)

            with torch.no_grad():
                z = torch.zeros((xb.size(0), 1), device=cfg.device)
                wmse = F.mse_loss(model(xb, z, z, cfg.temperature)[0], prev_yb) # Lagged
            dh, de, derr, dh_val, s2, dtau = tracker.compute(xb, wmse)
            de_t = torch.full((xb.size(0), 1), derr, device=cfg.device)

            with torch.no_grad(): py, pg, _, pe = model(xb, dh, de_t, cfg.temperature)
            ee, gap = exp_signals(prev_yb, py, pe, pg) # Lagged
            phi = phi_signal(de, derr, ee, gap, cfg); t_now = cfg.temp_stable + (cfg.temp_transition - cfg.temp_stable) * float(phi.item())

            pi = torch.cat([xb, dh, de_t, torch.full((xb.size(0),1), float(phi.item()), device=xb.device), torch.full((xb.size(0),1), s2, device=xb.device), torch.full((xb.size(0),1), dtau, device=xb.device)], dim=-1)
            ss, tp, mp = model.policy(pi)

            yh, gp, _, eo = model(xb, dh, de_t, t_now)
            eff = cfg.policy_mix_weight * float(ss[:, 1].mean().item())
            tgt = (F.one_hot(torch.argmax(tp.mean(0)), cfg.num_experts).float().unsqueeze(0).expand(xb.size(0), -1) - gp).detach() + gp
            mx = (1.0 - eff)*gp + eff*tgt
            final_r = F.one_hot(mx.argmax(-1), cfg.num_experts).float() if (cfg.use_hard_switch and (mp[:, 1].mean().item() > 0.5) and not (dh_val > cfg.phi_hard_threshold)) else mx
            yh = (final_r.unsqueeze(-1) * eo).sum(1)

            # Backward pass
            _, gl = exp_signals(yb, yh, eo, final_r)
            sl, cl = reg_stats(final_r, rb)
            sw_l, tg_l, md_l = pol_targets(prev_yb, pe, phi, s2, dtau, cfg) # Lagged

            loss = (F.mse_loss(yh, yb)
                  + cfg.beta_phi * (phi.detach() * gl) + cfg.alpha_dogma * compute_dogma_penalty(final_r) - cfg.beta_nomad * compute_nomad_bonus(final_r)
                  + cfg.gamma_diversity * div_loss(eo) + cfg.lambda_sep * sl + cfg.lambda_cons * cl + cfg.lambda_load * final_r.mean(0).var()
                  + cfg.policy_weight_stay * F.nll_loss(torch.log(ss + 1e-8), torch.full((xb.size(0),), sw_l, dtype=torch.long, device=cfg.device))
                  + cfg.policy_weight_target * F.nll_loss(torch.log(tp + 1e-8), torch.full((xb.size(0),), int(tg_l.item()), dtype=torch.long, device=cfg.device))
                  + cfg.policy_weight_mode * F.nll_loss(torch.log(mp + 1e-8), torch.full((xb.size(0),), md_l, dtype=torch.long, device=cfg.device))
                  - dw.compute(final_r, tau_dynamic=dtau if cfg.use_dynamic_tau else float(cfg.tau_k_min)))
            loss.backward(); opt.step()
            prev_yb = yb.detach()

        s_mse, dyn = eval_nomadic(model, splits, phase_tags, cfg, use_policy=True)
        mse_log.append(s_mse); dyn_log.append(dyn)
        if (epoch+1) % 55 == 0 or epoch == 0:
            print(f'  [Nomadic] Ep {epoch+1:03d} | MSE: {s_mse:.4f} | StableH: {dyn["stable_entropy_mean"]:.4f} | TransH: {dyn["transition_entropy_mean"]:.4f}')
    return model, mse_log, dyn_log

def train_stdmoe(cfg, splits, phase_tags):
    X_tr, Y_tr = splits['train']['X'], splits['train']['Y']
    model = StandardMoE(cfg.input_dim, cfg.hidden_dim, cfg.output_dim, cfg.num_experts, cfg.gate_hidden_dim).to(cfg.device)
    opt = torch.optim.Adam(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    mse_log, dyn_log = [], []
    for epoch in range(cfg.epochs):
        model.train()
        for i in range(0, len(X_tr), cfg.batch_size):
            xb, yb = X_tr[i:i+cfg.batch_size], Y_tr[i:i+cfg.batch_size]; opt.zero_grad()
            yh, gp, _, eo = model(xb)
            (F.mse_loss(yh, yb) + cfg.gamma_diversity * div_loss(eo) + cfg.lambda_load * gp.mean(0).var()).backward(); opt.step()
        s_mse, dyn = eval_stdmoe(model, splits, phase_tags, cfg)
        mse_log.append(s_mse); dyn_log.append(dyn)
    return model, mse_log, dyn_log

def eval_stdmoe(model, splits, phase_tags, cfg):
    model.eval(); X, Y, R = splits['test']['X'], splits['test']['Y'], splits['test']['R']
    ys, ents, tags = [], [], []
    with torch.no_grad():
        for i in range(0, len(X), cfg.batch_size):
            xb = X[i:i+cfg.batch_size]
            yh, gp, _, _ = model(xb); ys.append(yh)
            bi = i // cfg.batch_size; tags.append(phase_tags[bi] if bi < len(phase_tags) else 'stable_unknown')
            ents.append(gate_entropy(gp).mean().item())
    s_h = [e for t, e in zip(tags, ents) if t.startswith('stable_')]
    tr_h = [e for t, e in zip(tags, ents) if t.startswith('transition_')]
    return F.mse_loss(torch.cat(ys), Y).item(), {'stable_entropy_mean': float(np.mean(s_h)) if s_h else float('nan'), 'transition_entropy_mean': float(np.mean(tr_h)) if tr_h else float('nan'), 'mean_switch_latency': 0.0}

