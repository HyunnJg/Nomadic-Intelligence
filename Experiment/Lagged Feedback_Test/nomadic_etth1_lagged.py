class HybridDeltaTracker:
    def __init__(self, cfg, dev): self.cfg, self.dev = cfg, dev; self.reset()
    def reset(self): self.px = None; self.err_e = 0.0; self.err_b = 0.0; self.vw = []
    def compute(self, xb, mse):
        xm = xb.mean(0); de = 0.0 if self.px is None else float((xm - self.px).norm(2).item()); self.px = xm.detach()
        mv = float(mse.item() if isinstance(mse, torch.Tensor) else mse)
        self.err_e = self.cfg.ema_decay * self.err_e + (1 - self.cfg.ema_decay) * mv
        self.err_b = self.cfg.err_baseline_momentum * self.err_b + (1 - self.cfg.err_baseline_momentum) * self.err_e
        derr = float(max(0.0, self.err_e - self.err_b))
        dh = math.tanh(self.cfg.w_env * de + self.cfg.w_err * derr)
        self.vw.append(de); self.vw = self.vw[-self.cfg.tau_var_window:]
        s2 = float(np.var(self.vw)) if len(self.vw) > 1 else 0.0
        dtau = self.cfg.tau_min + (self.cfg.tau_max - self.cfg.tau_min) * math.exp(-self.cfg.tau_var_scale * s2)
        return torch.full((xb.size(0), 1), dh, device=self.dev), de, derr, dh, s2, dtau

class DwellTimeRegularizer:
    def __init__(self, min_t, pen): self.min_t, self.pen = min_t, pen; self.reset()
    def reset(self): self.cur, self.cnt = None, 0
    def compute(self, gp, dtau=None):
        t1 = int(gp.argmax(-1).float().mean().round().item())
        if self.cur is None or t1 != self.cur: self.cur, self.cnt = t1, 1
        else: self.cnt += 1
        return torch.tensor(self.pen if self.cnt >= (dtau if dtau is not None else float(self.min_t)) else 0.0, dtype=torch.float32, device=gp.device)

def gate_entropy(gp): return -(gp * (gp + 1e-8).log()).sum(-1)
def phi_signal(de, derr, ee, gap, cfg): return torch.tensor(math.tanh(cfg.phi_scale_env * de + cfg.phi_scale_err * derr + cfg.phi_scale_explain * float(ee.item() if isinstance(ee, torch.Tensor) else ee) + cfg.phi_scale_gap * float(gap.item() if isinstance(gap, torch.Tensor) else gap)), dtype=torch.float32, device=cfg.device)
def exp_signals(yb, yhat, eo, gp):
    with torch.no_grad():
        t_l = F.mse_loss(yhat, yb); pe = torch.stack([F.mse_loss(eo[:, k, :], yb) for k in range(eo.size(1))])
        gap = F.relu(pe[gp.argmax(-1).float().mean().long()] - pe.min())
    return t_l, gap
def div_loss(eo): return sum(-F.cosine_similarity(eo[:, i, :], eo[:, j, :], dim=-1).mean() for i in range(eo.size(1)) for j in range(i+1, eo.size(1))) / max(1, eo.size(1)*(eo.size(1)-1)//2)
def reg_stats(gp, r_lbl):
    ur = r_lbl.unique(); sl = torch.tensor(0.0, device=gp.device); cl = torch.tensor(0.0, device=gp.device)
    if len(ur) < 2: return sl, cl
    rm = [gp[r_lbl == r].mean(0) for r in ur if (r_lbl == r).sum() > 0]
    if len(rm) >= 2: sl = -sum(F.cosine_similarity(rm[i].unsqueeze(0), rm[j].unsqueeze(0)).mean() for i in range(len(rm)) for j in range(i+1, len(rm))) / max(1, len(rm)*(len(rm)-1)//2)
    cl = sum(gp[r_lbl == r].var(0).mean() for r in ur if (r_lbl == r).sum() > 1)
    return sl, cl
def pol_targets(yb, eo, phi, s2, dtau, cfg):
    pv = float(phi.item() if isinstance(phi, torch.Tensor) else phi)
    return 1 if pv > cfg.phi_hard_threshold else 0, torch.stack([F.mse_loss(eo[:, k, :], yb) for k in range(eo.size(1))]).argmin(), 1 if (s2 < 0.01 and dtau > cfg.tau_min + 1) else 0

