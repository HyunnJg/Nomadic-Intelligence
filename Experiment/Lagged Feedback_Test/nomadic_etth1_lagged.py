def load_etth1_data(csv_path: str, cfg: Config):
    df = pd.read_csv(csv_path); df['date'] = pd.to_datetime(df['date']); df = df.sort_values('date').reset_index(drop=True)
    feature_cols = ['HUFL', 'HULL', 'MUFL', 'MULL', 'LUFL', 'LULL', 'OT']

    df['roll_std'] = df['OT'].rolling(cfg.roll_window).std(); df = df.dropna(subset=['roll_std']).reset_index(drop=True)
    df['target'] = df['OT'].shift(-24); df = df.dropna(subset=['target']).reset_index(drop=True)

    n_train = int(len(df) * cfg.train_ratio)
    p33, p67 = df['roll_std'].iloc[:n_train].quantile(0.33), df['roll_std'].iloc[:n_train].quantile(0.67)
    df['regime'] = 0; df.loc[df['roll_std'] >= p33, 'regime'] = 1; df.loc[df['roll_std'] >= p67, 'regime'] = 2

    X_raw, Y_raw, R_raw = df[feature_cols].values.astype(np.float32), df['target'].values.astype(np.float32).reshape(-1, 1), df['regime'].values.astype(np.int64)
    x_mean, x_std = X_raw[:n_train].mean(axis=0), X_raw[:n_train].std(axis=0) + 1e-8
    y_mean, y_std = Y_raw[:n_train].mean(), Y_raw[:n_train].std() + 1e-8

    return (X_raw - x_mean) / x_std, (Y_raw - y_mean) / y_std, R_raw, df['date'].values

def split_data(X, Y, R, dates, cfg: Config):
    n = len(X); n_train, n_val = int(n * cfg.train_ratio), int(n * cfg.val_ratio)
    def to_tensor(arr, dtype=torch.float32): return torch.tensor(arr, dtype=dtype).to(cfg.device)

    splits = {}
    for name, s, e in [('train', 0, n_train), ('val', n_train, n_train + n_val), ('test', n_train + n_val, n)]:
        splits[name] = {'X': to_tensor(X[s:e]), 'Y': to_tensor(Y[s:e]), 'R': to_tensor(R[s:e], dtype=torch.long), 'n': e - s}
    return splits

def generate_phase_tags(R_tensor, window=2):
    R = R_tensor.cpu().numpy() if isinstance(R_tensor, torch.Tensor) else R_tensor
    mapping = {0: 'LowVol', 1: 'MidVol', 2: 'HighVol'}
    tags = [f"stable_{mapping[R[i]]}" for i in range(len(R))]
    for i in range(1, len(R)):
        if R[i] != R[i-1]:
            for j in range(max(0, i-window), min(len(R), i+window+1)):
                tags[j] = f"transition_{mapping[R[i-1]]}_to_{mapping[R[i]]}"
    return tags

