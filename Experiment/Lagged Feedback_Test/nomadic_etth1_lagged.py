class Expert(nn.Module):
    def __init__(self, in_d, h, out_d):
        super().__init__(); self.net = nn.Sequential(nn.Linear(in_d, h), nn.Tanh(), nn.Linear(h, h), nn.Tanh(), nn.Linear(h, out_d))
    def forward(self, x): return self.net(x)

class GateNet(nn.Module):
    def __init__(self, in_d, h, n_exp):
        super().__init__(); self.net = nn.Sequential(nn.Linear(in_d + 2, h), nn.ReLU(), nn.Linear(h, h), nn.ReLU(), nn.Linear(h, n_exp))
    def forward(self, x, dh, de, temp):
        logits = self.net(torch.cat([x, dh, de], dim=-1)); return F.softmax(logits / temp, dim=-1), logits

class PolicyNet(nn.Module):
    def __init__(self, in_d, h, n_exp):
        super().__init__(); self.shared = nn.Sequential(nn.Linear(in_d + 5, h), nn.ReLU(), nn.Linear(h, h), nn.ReLU())
        self.ss_head, self.tgt_head, self.mode_head = nn.Linear(h, 2), nn.Linear(h, n_exp), nn.Linear(h, 2)
    def forward(self, x):
        h = self.shared(x); return F.softmax(self.ss_head(h), dim=-1), F.softmax(self.tgt_head(h), dim=-1), F.softmax(self.mode_head(h), dim=-1)

class StandardMoE(nn.Module):
    def __init__(self, in_d, h, out_d, n_exp, g_h):
        super().__init__(); self.n_exp = n_exp; self.experts = nn.ModuleList([Expert(in_d, h, out_d) for _ in range(n_exp)])
        self.gate = nn.Sequential(nn.Linear(in_d, g_h), nn.ReLU(), nn.Linear(g_h, g_h), nn.ReLU(), nn.Linear(g_h, n_exp))
    def forward(self, x):
        gp = F.softmax(self.gate(x), dim=-1); eo = torch.stack([e(x) for e in self.experts], dim=1)
        return (gp.unsqueeze(-1) * eo).sum(1), gp, self.gate(x), eo

class NomadicMoE(nn.Module):
    def __init__(self, in_d, h, out_d, n_exp, g_h, p_h):
        super().__init__(); self.n_exp = n_exp; self.experts = nn.ModuleList([Expert(in_d, h, out_d) for _ in range(n_exp)])
        self.gate = GateNet(in_d, g_h, n_exp); self.policy = PolicyNet(in_d, p_h, n_exp)
    def forward(self, x, dh, de, temp):
        gp, gl = self.gate(x, dh, de, temp); eo = torch.stack([e(x) for e in self.experts], dim=1)
        return (gp.unsqueeze(-1) * eo).sum(1), gp, gl, eo

